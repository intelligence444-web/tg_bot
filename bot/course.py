def card_for(day: int) -> Card | None:
    """Карточка дня ``day`` (с 1) или ``None``, если её ещё нет."""
    if 1 <= day <= len(CARDS):
        return CARDS[day - 1]
    return None


def format_card(day: int, card: Card) -> str:
    """Текст сообщения в HTML (parse_mode="HTML"); поля карточки экранируются."""
    return texts.CARD_TEMPLATE.format(
        day=day,
        total=COURSE_LENGTH,
        title=html.escape(card.title, quote=False),
        body=html.escape(card.body, quote=False),
        tip=html.escape(card.tip, quote=False),
    )
